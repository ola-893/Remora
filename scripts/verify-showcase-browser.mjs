import assert from 'node:assert/strict';
import { parseArgs } from 'node:util';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
const { values: v } = parseArgs({ options: { driver: { type: 'string' }, browser: { type: 'string' }, 'package-root': { type: 'string' }, run: { type: 'string', default: 'docs/evidence/near/repository-showcase-testnet.json' } } });
const { startUi } = await import(v['package-root'] ? pathToFileURL(join(resolve(v['package-root']), 'src/ui.mjs')) : new URL('../packages/cli/src/ui.mjs', import.meta.url));
if (!v.driver) throw new Error('Provide --driver /path/to/playwright-core/index.mjs (development-only dependency).');
const { chromium } = await import(pathToFileURL(resolve(v.driver)));
const out = resolve('docs/evidence/near/showcase-browser'); await mkdir(out, { recursive: true });
const result = { checkedAt: new Date().toISOString(), engine: 'Chromium via Playwright', installedPackage: Boolean(v['package-root']), checks: {}, errors: [], screenshots: [] };
const ui = await startUi({ runFile: resolve(v.run) });
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(v.browser ? { executablePath: v.browser } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on('pageerror', error => result.errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') result.errors.push(message.text()); });
  await page.goto(ui.url); await page.getByRole('heading', { name: 'A paid tool. Actual findings.' }).waitFor();
  await page.screenshot({ path: join(out, 'desktop.png') }); result.screenshots.push('desktop.png');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  result.checks.analysisPanelContrast = await page.locator('.ap-product-proof h2').evaluate(element => {
    const rgb = value => value.match(/[\d.]+/g).slice(0, 3).map(Number).map(v => { const n = v / 255; return n <= .04045 ? n / 12.92 : ((n + .055) / 1.055) ** 2.4; });
    const luminance = value => { const [r, g, b] = rgb(value); return .2126*r + .7152*g + .0722*b; };
    const foreground = luminance(getComputedStyle(element).color), background = luminance(getComputedStyle(element.closest('.ap-product-proof')).backgroundColor);
    return (Math.max(foreground, background) + .05) / (Math.min(foreground, background) + .05) >= 4.5;
  });
  assert.equal(result.checks.analysisPanelContrast, true);
  const inspect = page.getByRole('button', { name: 'Inspect analysis evidence' });
  await inspect.click(); const drawer = page.getByRole('dialog'); await drawer.waitFor({ state: 'visible' });
  assert.ok(await drawer.locator('.ap-finding').count());
  await page.screenshot({ path: join(out, 'findings.png') }); result.screenshots.push('findings.png');
  await page.keyboard.press('Escape'); await drawer.waitFor({ state: 'hidden' });
  assert.equal(await inspect.evaluate(element => element === document.activeElement), true);
  result.checks.findingsDrawerAndFocusRestoration = true;
  const search = page.getByRole('textbox', { name: 'Search execution history' });
  await search.fill('RECIPIENT_DENIED');
  const rejection = page.getByRole('button', { name: /Inspect Policy checkpoint/ }).first();
  await rejection.click(); await drawer.waitFor({ state: 'visible' });
  const link = drawer.getByRole('link', { name: 'Inspect contract rejection' });
  assert.match(await link.getAttribute('href'), /^https:\/\/testnet.nearblocks.io\/txns\//);
  result.checks.rejectedContractReceiptLinked = true;
  await drawer.getByRole('button', { name: 'Close evidence' }).click();
  await search.fill('SERVICE_5XX_LIMIT');
  assert.ok(await page.locator('.ap-history-list button, .ap-history button').count() || await page.getByRole('button', { name: /Inspect Policy checkpoint/ }).count());
  await search.fill('no-such-event-12345'); await page.getByText('No matching events', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Reset all filters' }).click();
  result.checks.searchAndEmptyStateReset = true;
  await page.getByRole('link', { name: /How it works/ }).click();
  await page.waitForURL('**/docs');
  assert.ok((await page.textContent('body')).includes('NEAR'));
  await page.goto(ui.url);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('heading', { name: 'A paid tool. Actual findings.' }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button', { name: 'Inspect analysis evidence' }).click();
  await page.getByRole('dialog').waitFor({ state: 'visible' });
  await page.screenshot({ path: join(out, 'mobile-findings.png') }); result.screenshots.push('mobile-findings.png');
  await page.getByRole('button', { name: 'Close evidence' }).click();
  result.checks.desktopAndMobileNoHorizontalOverflow = true;
  result.checks.docsNavigation = true;
  assert.equal((await fetch(ui.url + '/api/near/run', { method: 'POST' })).status, 405);
  result.checks.replayCannotSign = true;
  assert.deepEqual(result.errors, []);
  result.passed = true;
} catch (error) { result.error = error.message; result.passed = false; process.exitCode = 1; }
finally { await browser?.close(); await ui.close(); await writeFile(join(out, 'verification.json'), JSON.stringify(result, null, 2) + '\n'); console.log(JSON.stringify(result)); }
